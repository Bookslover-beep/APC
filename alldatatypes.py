#All data types simple Program

#Interger
a=10
print(f"a = {a}")
print(type(a))
print()

#Float
b=20.75
print(f"b = {b}")
print(type(b))
print()

#Complex
c = 3 + 4j
print(f"c = {c}")
print(type(c))
print()

#String
s="Hello!"
print(f"s = {s}")
print(type(s))
print()

#List
l=[1,2,3,"Hello World!"]
print(f"l = {l}")
print(type(l))
print()

#Tuple
t=('p','q','r',1,2,3,"Hii")
print(f"t = {t}")
print(type(t))
print()

#Boolean
bool=True
print(f"bool = {bool}")
print(type(bool))
print()

#Range
r=range(9)
print(r)
print(type(r))
print("r = ",list(r))
print()

#Dictionary
dict={"Name":"Prajakta" ,"Surname": "Magar"}
print(f"dict = {dict}")
print(type(dict))
print()

#Set 
st = {1,2,3,4,5}
print(f"st = {st}")
print(type(st))
print()

#Frozen set
fs = frozenset({1,2,3})
print(f"fs = {fs}")
print(type(fs))
print()

#Bytes
byte = b"Python"
print(f"byte = {byte}")
print(type(byte))
print()

#Bytearray
ba = bytearray(5)
print(ba)
print(type(ba))
print()

#Memoryview
mv = memoryview(bytes(5))
print(mv)
print(type(mv))
print()

#NoneType
n = None
print(f"n = {n}")
print(type(n))





